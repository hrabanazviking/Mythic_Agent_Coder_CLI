from mythic_agent.core.sessions import SessionStore


def store_for(tmp_path, workspace=None):
    return SessionStore(workspace or tmp_path, tmp_path / "state")


class TestAgentGate:
    def test_status(self, agent):
        status = agent.generated_code_status()
        assert status["enabled"] is True
        assert status["explanation"] == gc.PLAIN_EXPLANATION

    def test_set_without_session(self, agent):
        record = agent.set_generated_code(False)
        assert record["journaled"] is False
        assert agent.config["generated_code"] is False
        with pytest.raises(ValueError, match="already"):
            agent.set_generated_code(False)

    def test_set_journals_on_the_session(self, agent, tmp_path):
        store = store_for(tmp_path)
        session_id = agent.attach_session(store)
        agent.set_generated_code(False)
        types = [e["type"] for e in store.export(session_id)["events"]]
        assert "generated_code_setting_changed" in types
        agent.close()

    def test_save_failure_restores_and_journals_the_revert(
            self, agent, tmp_path, monkeypatch):
        from mythic_agent.agents import llm

        store = store_for(tmp_path)
        session_id = agent.attach_session(store)
        monkeypatch.setattr(llm.config_manager, "save_config",
                            lambda config: False)
        with pytest.raises(RuntimeError, match="could not be saved"):
            agent.set_generated_code(False)
        assert agent.config.get("generated_code") is not False
        types = [e["type"] for e in store.export(session_id)["events"]]
        assert types[-2:] == ["generated_code_setting_changed",
                              "generated_code_setting_reverted"]
        agent.close()


class TestAgentCheckMark:
    def test_check_generated_file(self, agent, tmp_path):
        (tmp_path / "out.py").write_text(
            "# Generated by gen1\nx = 1\n", encoding="utf-8")
        data = agent.check_generated_code("out.py")
        assert data["is_generated"] is True
        assert data["generator"] == "gen1"
        assert data["assessment"]["warns"] is True
        assert "gen1" in data["assessment"]["warning"]

    def test_check_plain_file(self, agent, tmp_path):
        (tmp_path / "app.py").write_text("x = 1\n", encoding="utf-8")
        data = agent.check_generated_code("app.py")
        assert data["is_generated"] is False
        assert data["assessment"]["warns"] is False

    def test_check_missing_file_refuses(self, agent):
        with pytest.raises(ValueError, match="does not exist"):
            agent.check_generated_code("nope.py")

    def test_mark_writes_header_and_journals(self, agent, tmp_path):
        (tmp_path / "out.py").write_text("x = 1\n", encoding="utf-8")
        store = store_for(tmp_path)
        session_id = agent.attach_session(store)
        data = agent.mark_generated_file("out.py", "gen1")
        assert data["marked"] is True
        assert data["journaled"] is True
        text = (tmp_path / "out.py").read_text(encoding="utf-8")
        assert text.startswith("# Generated by gen1")
        assert text.endswith("x = 1\n")
        types = [e["type"] for e in store.export(session_id)["events"]]
        assert "generated_file" in types
        agent.close()

    def test_mark_already_marked_writes_nothing(self, agent, tmp_path):
        original = "# Generated by gen1\nx = 1\n"
        (tmp_path / "out.py").write_text(original, encoding="utf-8")
        data = agent.mark_generated_file("out.py", "gen1")
        assert data["marked"] is False
        assert (tmp_path / "out.py").read_text(
            encoding="utf-8") == original

    def test_mark_conflicting_generator_refuses(self, agent, tmp_path):
        (tmp_path / "out.py").write_text(
            "# Generated by gen1\nx = 1\n", encoding="utf-8")
        with pytest.raises(ValueError, match="already marked"):
            agent.mark_generated_file("out.py", "other")

    def test_mark_gate_off_refuses(self, agent, tmp_path):
        (tmp_path / "out.py").write_text("x = 1\n", encoding="utf-8")
        agent.set_generated_code(False)
        with pytest.raises(ValueError, match="generated-code honesty is off"):
            agent.mark_generated_file("out.py", "gen1")
        assert (tmp_path / "out.py").read_text(
            encoding="utf-8") == "x = 1\n"


class TestSaveWarning:
    PAYLOAD = "@@ -1,2 +1,2 @@\n # Generated by gen1\n-x = 1\n+x = 2\n"

    def test_edit_to_generated_file_warns_before_saving(
            self, agent, tmp_path):
        (tmp_path / "out.py").write_text(
            "# Generated by gen1\nx = 1\n", encoding="utf-8")
        record = agent.apply_edit_format(
            "out.py", "unified-diff", self.PAYLOAD)
        assert record["generated_warning"] is not None
        assert "gen1" in record["generated_warning"]
        assert (tmp_path / "out.py").read_text(
            encoding="utf-8").endswith("x = 2\n")

    def test_edit_to_plain_file_has_no_warning(self, agent, tmp_path):
        (tmp_path / "app.py").write_text("x = 1\n", encoding="utf-8")
        record = agent.apply_edit_format(
            "app.py", "search-replace",
            "<<<<<<< SEARCH\nx = 1\n=======\nx = 2\n>>>>>>> REPLACE\n")
        assert record["generated_warning"] is None

    def test_gate_off_suppresses_the_save_warning(self, agent, tmp_path):
        (tmp_path / "out.py").write_text(
            "# Generated by gen1\nx = 1\n", encoding="utf-8")
        agent.set_generated_code(False)
        record = agent.apply_edit_format(
            "out.py", "unified-diff", self.PAYLOAD)
        assert record["generated_warning"] is None


