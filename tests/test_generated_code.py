"""Tests for M-086: generated-code honesty.

TIER: integration
"""

import pytest

from mythic_agent.core import generated_code as gc


def test_detect_generated_by_line_names_generator():
    marker = gc.detect_marker("# Generated by build_tool v2\nx = 1\n")
    assert marker is not None
    assert marker.form == "generated_by"
    assert marker.generator == "build_tool v2"
    assert marker.line_number == 1


def test_detect_do_not_edit_alone_has_unknown_generator():
    marker = gc.detect_marker("// DO NOT EDIT\nint x;\n")
    assert marker is not None
    assert marker.form == "do_not_edit"
    assert marker.generator is None


def test_detect_generated_tag_with_generator():
    marker = gc.detect_marker("@generated proto-compiler\n")
    assert marker is not None
    assert marker.form == "generated_tag"
    assert marker.generator == "proto-compiler"


def test_detect_this_file_is_generated():
    marker = gc.detect_marker("This file is generated by schema_gen.\n")
    assert marker is not None
    assert marker.generator == "schema_gen"


def test_marker_deep_in_file_does_not_classify():
    text = "\n".join(["x = 1"] * 20 + ["# Generated by late_tool"])
    assert gc.detect_marker(text) is None


def test_plain_file_has_no_marker():
    assert gc.detect_marker("def main():\n    return 1\n") is None


def test_detect_marker_rejects_non_string():
    with pytest.raises(ValueError):
        gc.detect_marker(None)


def test_classify_generated_file_records_generator():
    record = gc.classify_text("build/out.py", "# Generated by gen1\n")
    assert record.is_generated is True
    assert record.generator == "gen1"
    data = record.record()
    assert data["slice"] == "M-086"
    assert data["marker"]["form"] == "generated_by"


def test_classify_plain_file_is_honest_absence():
    record = gc.classify_text("src/app.py", "x = 1\n")
    assert record.is_generated is False
    assert record.generator is None
    assert record.record()["marker"] is None


@pytest.mark.parametrize("bad", ["/abs/x.py", "../x.py", "a//b.py", ""])
def test_classify_refuses_dirty_paths(bad):
    with pytest.raises(ValueError):
        gc.classify_text(bad, "x = 1\n")


def test_register_generated_records_name():
    record = gc.register_generated("build/out.py", "gen1")
    assert record.is_generated is True
    assert record.generator == "gen1"


def test_register_generated_refuses_empty_generator():
    with pytest.raises(ValueError):
        gc.register_generated("build/out.py", "  ")


def test_register_generated_conflicting_marker_refuses():
    with pytest.raises(ValueError, match="already marked"):
        gc.register_generated("build/out.py", "other",
                              text="# Generated by gen1\n")


def test_marker_header_uses_comment_style_and_names_generator():
    header = gc.marker_header("build/out.py", "gen1")
    assert header.startswith("# Generated by gen1")
    assert "do not edit" in header.lower()
    assert gc.marker_header("build/out.js", "gen1").startswith("// ")


def test_assess_edit_warns_for_generated_file():
    record = gc.classify_text("build/out.py", "# Generated by gen1\n")
    assessment = gc.assess_edit(record)
    assert assessment.warns is True
    assert "gen1" in assessment.warning
    assert "overwritten" in assessment.warning


def test_assess_edit_silent_for_plain_file():
    record = gc.classify_text("src/app.py", "x = 1\n")
    assessment = gc.assess_edit(record)
    assert assessment.warns is False
    assert assessment.warning is None


def test_assess_edit_gate_off_suppresses_warning_not_classification():
    record = gc.classify_text("build/out.py", "# Generated by gen1\n")
    assessment = gc.assess_edit(record, config={"generated_code": False})
    assert assessment.warns is False
    assert assessment.is_generated is True


def test_assess_edit_unknown_generator_warns_honestly():
    record = gc.classify_text("build/out.py", "# DO NOT EDIT\n")
    assessment = gc.assess_edit(record)
    assert assessment.warns is True
    assert "not recorded" in assessment.warning


def test_enabled_from_config_defaults_on_and_rejects_non_bool():
    assert gc.enabled_from_config({}) is True
    assert gc.enabled_from_config({"generated_code": False}) is False
    with pytest.raises(ValueError):
        gc.enabled_from_config({"generated_code": "yes"})


def test_set_enabled_change_and_noop_refusal():
    value, change = gc.set_enabled({}, False)
    assert value is False
    assert change.event()["type"] == "generated_code_setting_changed"
    with pytest.raises(ValueError, match="already on"):
        gc.set_enabled({}, True)
    with pytest.raises(ValueError):
        gc.set_enabled({}, "off")


def test_parse_show_on_off():
    assert gc.parse_generated_args("") == {"action": "show"}
    assert gc.parse_generated_args("on") == {"action": "on"}
    assert gc.parse_generated_args("off") == {"action": "off"}


def test_parse_check_and_mark():
    assert gc.parse_generated_args("build/out.py") == {
        "action": "check", "path": "build/out.py"}
    parsed = gc.parse_generated_args("mark build/out.py my gen tool")
    assert parsed == {"action": "mark", "path": "build/out.py",
                      "generator": "my gen tool"}


def test_parse_usage_errors():
    with pytest.raises(ValueError, match="usage"):
        gc.parse_generated_args("mark onlypath")
    with pytest.raises(ValueError, match="usage"):
        gc.parse_generated_args("a b c")


def test_format_generated_record_and_warning():
    record = gc.classify_text("build/out.py", "# Generated by gen1\n")
    text = gc.format_generated_record(record)
    assert "generated by gen1" in text
    warning = gc.format_edit_warning(gc.assess_edit(record))
    assert warning.startswith("Warning before saving:")
    plain = gc.classify_text("src/app.py", "x = 1\n")
    assert "not marked" in gc.format_generated_record(plain)
    assert "no generated-file warning" in gc.format_edit_warning(
        gc.assess_edit(plain))


def test_format_setting_change():
    assert gc.format_setting_change({"to": False}) == (
        "Generated-code honesty is now off.")


def test_format_generated_code_show_surface():
    text = gc.format_generated_code({})
    assert "M-086" in text
    assert "Setting: on" in text
    assert "build_tool v2" in text
    assert "Warning before saving" in text
    off = gc.format_generated_code({"generated_code": False})
    assert "Setting: off" in off
    assert "no generated-file warning" in off
